def build_networkx_graph(nodes: List[GridNode], edges: List[TransmissionLine]) -> nx.Graph:
    """Builds a NetworkX graph with rich electrical and operational attributes."""
    G = nx.Graph()

    for node in nodes:
        G.add_node(
            node.id,
            id=node.id,
            name=node.name,
            type=node.type,
            voltage_kv=node.voltage_kv,
            demand_mw=node.demand_mw,
            generation_mw=node.generation_mw,
            capacity_mw=node.capacity_mw,
            priority=node.priority,
            criticality=node.criticality,
            status=node.status,
            backup_availability=node.backup_availability,
            backup_capacity_mw=node.backup_capacity_mw,
            backup_active=node.backup_active,
            power_served_mw=node.power_served_mw,
            is_energized=node.is_energized,
            substation_id=node.substation_id,
        )

    for edge in edges:
        G.add_edge(
            edge.source,
            edge.target,
            id=edge.id,
            name=edge.name,
            voltage_kv=edge.voltage_kv,
            capacity_mw=edge.capacity_mw,
            current_flow_mw=edge.current_flow_mw,
            status=edge.status,
            failed=edge.failed,
            restoration_time_min=edge.restoration_time_min,
            distance_km=edge.distance_km,
            tower_ids=edge.tower_ids,
        )

    return G


def get_default_topology() -> GridTopologyResponse:
    """Returns the complete default GridTopologyResponse."""
    nodes = get_default_nodes()
    edges = get_default_edges()
    towers = get_default_towers()
    return GridTopologyResponse(nodes=nodes, edges=edges, towers=towers)
